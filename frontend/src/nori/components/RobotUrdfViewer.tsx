/**
 * Renders the real Nori robot description.
 *
 * Deliberately NOT the upstream `UrdfViewer`: that one is bound to LeLab's
 * drag-and-drop context, defaults to the SO-101 arm, and opens a websocket for
 * live joint streaming. None of that applies to showing one fixed, shipped model.
 *
 * Presentation is matched to `nori/remote/Robot3D` (the stylised model on the
 * remote page) so the two read as the same robot: same palette, same lighting,
 * same long-lens low-angle framing. The palette below mirrors the constants in
 * packages/nori-sdk/src/robot-model.ts — if those change, change these.
 *
 * Assets are static files under `public/nori-urdf/`, generated by
 * `nori_ws/urdf_release/tools/sync_to_lelab.py`. Re-run it when the model changes.
 */

